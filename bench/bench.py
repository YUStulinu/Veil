"""Benchmarks: the MSM and NTT kernels (CPU and CUDA), the prover on
synthetic circuits of 2^k rows, the Sudoku proof with the ceremony's SRS,
and the verifiers (Rust, TypeScript, EVM gas). Writes results/bench.json,
results/README.md and results/bench.png.

    python bench/bench.py [--quick]
    python bench/bench.py --report        (only rewrite the report)

Needs prover/target/release/veil built with --features cuda for the GPU
columns (without a GPU they are left out), and scripts/sudoku.sh plus the
evm/ and web/ tests for the Sudoku, gas and browser numbers.
"""

import argparse
import json
import os
import platform
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = ".exe" if os.name == "nt" else ""
VEIL = os.path.join(ROOT, "prover", "target", "release", "veil" + EXE)
VEILC = os.path.join(ROOT, "lang", "build", "veilc" + EXE)
OUT = os.path.join(ROOT, "results")


def run_json(*args):
    out = subprocess.run([VEIL, *args], check=True, capture_output=True, text=True).stdout
    return json.loads(out.strip().splitlines()[-1])


def has_gpu():
    r = subprocess.run([VEIL, "kernels", "--log-n", "12", "--gpu"], capture_output=True, text=True)
    return r.returncode == 0 and '"gpu_matches_cpu": true' in r.stdout


def sudoku(reps):
    times, verify = [], []
    for _ in range(reps):
        r = subprocess.run(
            [VEIL, "prove", "--circuit", "build/sudoku.circuit", "--inputs", "lang/examples/sudoku.inputs",
             "--srs", "ceremony:data/trusted_setup.txt", "--out", "build/proof.bin", "--public", "build/public.txt",
             "--vk", "build/vk.bin", "--evm", "build/proof.evm"],
            cwd=ROOT, check=True, capture_output=True, text=True)
        m = re.search(r"(\d+) rows, n = (\d+).*preprocessing ([\d.]+) s, proving ([\d.]+) s", r.stderr)
        rows, n = int(m[1]), int(m[2])
        times.append((float(m[3]), float(m[4])))
        v = subprocess.run([VEIL, "verify", "--vk", "build/vk.bin", "--proof", "build/proof.bin", "--public", "build/public.txt"],
                           cwd=ROOT, check=True, capture_output=True, text=True).stdout
        verify.append(float(re.search(r"([\d.]+) ms", v)[1]))
    gates = {}
    for name, flags in [("optimized", []), ("O0", ["-O0"])]:
        r = subprocess.run([VEILC, "lang/examples/sudoku.veil", *flags], cwd=ROOT, check=True, capture_output=True, text=True)
        gates[name] = int(re.search(r"(\d+) gates", r.stderr)[1])
    return {"rows": rows, "n": n, "gates": gates, "srs": "ethereum-kzg-ceremony",
            "preprocess_s": min(t[0] for t in times), "prove_s": min(t[1] for t in times), "verify_ms": min(verify)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    if a.report:
        report(json.load(open(os.path.join(OUT, "bench.json"))))
        return
    gpu = has_gpu()
    res = {"machine": {"cpu": platform.processor(), "threads": os.cpu_count(), "gpu": gpu}}
    res["kernels"] = []
    for k in [12, 14, 16, 18] if a.quick else [12, 14, 16, 18, 20, 22]:
        row = {"log_n": k, "cpu": run_json("kernels", "--log-n", str(k))}
        if gpu:
            row["gpu"] = run_json("kernels", "--log-n", str(k), "--gpu")
        res["kernels"].append(row)
        print("kernels", row, flush=True)
    res["prover"] = []
    for k in [10, 12, 14, 16] if a.quick else [10, 12, 14, 16, 18, 20]:
        row = {"log_n": k, "cpu": run_json("bench", "--log-n", str(k), "--reps", "2")}
        if gpu:
            row["gpu"] = run_json("bench", "--log-n", str(k), "--reps", "2", "--gpu")
        res["prover"].append(row)
        print("prover", row, flush=True)
    if os.path.exists(os.path.join(ROOT, "build", "sudoku.circuit")):
        res["sudoku"] = sudoku(3)
        print("sudoku", res["sudoku"], flush=True)
    for name in ["evm_gas", "web_timings"]:
        p = os.path.join(ROOT, "build", name + ".json")
        if os.path.exists(p):
            res[name] = json.load(open(p))
    os.makedirs(OUT, exist_ok=True)
    json.dump(res, open(os.path.join(OUT, "bench.json"), "w"), indent=1)
    report(res)


def report(res):
    gpu = res["machine"]["gpu"]
    L = ["# Veil: measured results", "",
         f"Generated by `bench/bench.py` on an {res['machine'].get('cpu_name', 'Intel Core i7-10870H')} ({res['machine']['threads']} threads)"
         + (" and an NVIDIA GeForce RTX 2060 (6 GB)." if gpu else "."), ""]
    s = res.get("sudoku")
    if s:
        L += ["## Sudoku (the demo)", "",
              f"The circuit `lang/examples/sudoku.veil`: {s['gates']['optimized']} gates ({s['gates']['O0']} without the compiler's "
              f"optimizations), {s['rows']} rows with the 81 public inputs, domain n = {s['n']}, SRS from the Ethereum KZG ceremony.", "",
              "| step | time |", "|---|---|",
              f"| preprocessing (native, CPU) | {s['preprocess_s'] * 1e3:.0f} ms |",
              f"| proving (native, CPU) | {s['prove_s'] * 1e3:.0f} ms |"]
        w = res.get("web_timings", {})
        if "wasm_prove_ms" in w:
            L.append(f"| proving in Wasm (Node, one thread, preprocessing included) | {w['wasm_prove_ms']} ms |")
        L.append(f"| verifying (Rust) | {s['verify_ms']:.1f} ms |")
        if "ts_verify_ms" in w:
            L.append(f"| verifying (TypeScript, BigInt) | {w['ts_verify_ms']} ms |")
        L.append("")
    g = res.get("evm_gas")
    if g:
        L += ["## On-chain verification (EVM, EIP-2537 precompiles)", "",
              "| measure | value |", "|---|---|",
              f"| execution gas | {g['execution_gas']:,} |",
              f"| calldata gas ({g['calldata_bytes']:,} bytes: the 1344-byte proof, 81 public inputs, ABI) | {g['calldata_gas']:,} |",
              f"| transaction total (+21,000) | {g['transaction_gas']:,} |",
              f"| deployed bytecode | {g['deployed_bytes']:,} bytes |", ""]
    L += ["## Prover on synthetic circuits", "",
          "All rows used (2^k - 3 gates, 2 public inputs, one equality), insecure local SRS. The proof is always 624 bytes.", "",
          "| rows | preprocessing CPU | prove CPU |" + (" preprocessing GPU | prove GPU | speedup |" if gpu else "") + " verify |",
          "|---|---|---|" + ("---|---|---|" if gpu else "") + "---|"]
    for r in res["prover"]:
        c = r["cpu"]
        line = f"| 2^{r['log_n']} | {c['preprocess_s']:.2f} s | {c['prove_s']:.2f} s |"
        if gpu:
            q = r["gpu"]
            line += f" {q['preprocess_s']:.2f} s | {q['prove_s']:.2f} s | {c['prove_s'] / q['prove_s']:.1f}x |"
        L.append(line + f" {c['verify_ms']:.1f} ms |")
    L += ["", "## Kernels (G1 MSM, Fr NTT)", "",
          "| size | MSM CPU |" + (" MSM GPU | speedup |" if gpu else "") + " NTT CPU |" + (" NTT GPU | speedup |" if gpu else ""),
          "|---|---|" + ("---|---|" if gpu else "") + "---|" + ("---|---|" if gpu else "")]
    for r in res["kernels"]:
        c = r["cpu"]
        line = f"| 2^{r['log_n']} | {c['msm_s'] * 1e3:.1f} ms |"
        if gpu:
            line += f" {r['gpu']['msm_s'] * 1e3:.1f} ms | {c['msm_s'] / r['gpu']['msm_s']:.1f}x |"
        line += f" {c['ntt_s'] * 1e3:.2f} ms |"
        if gpu:
            line += f" {r['gpu']['ntt_s'] * 1e3:.2f} ms | {c['ntt_s'] / r['gpu']['ntt_s']:.1f}x |"
        L.append(line)
    if gpu:
        L += ["", "GPU times include the copies between host and device. Every GPU result was compared with the CPU's (`gpu_matches_cpu`: "
              + ("all true" if all(r["gpu"]["gpu_matches_cpu"] for r in res["kernels"]) else "SOME FALSE") + ")."]
    L += ["", "![prover and kernels](bench.png)"]
    open(os.path.join(OUT, "README.md"), "w").write("\n".join(L) + "\n")
    plots(res)


def plots(res):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return
    gpu = res["machine"]["gpu"]
    cpu_c, gpu_c = "#2f5d8a", "#c0632b"
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    ks = [r["log_n"] for r in res["prover"]]
    ax = axes[0]
    ax.plot(ks, [r["cpu"]["prove_s"] for r in res["prover"]], "o-", color=cpu_c, lw=2, label="CPU, 16 threads")
    if gpu:
        ax.plot(ks, [r["gpu"]["prove_s"] for r in res["prover"]], "s-", color=gpu_c, lw=2, label="GPU for MSM and NTT")
    ax.set(yscale="log", xlabel="log2(rows)", ylabel="proving time (s)", title="Prover")
    ax.grid(alpha=0.3)
    ax.legend()
    ax = axes[1]
    kk = [r["log_n"] for r in res["kernels"]]
    ax.plot(kk, [r["cpu"]["msm_s"] for r in res["kernels"]], "o-", color=cpu_c, lw=2, label="MSM, CPU")
    ax.plot(kk, [r["cpu"]["ntt_s"] for r in res["kernels"]], "o--", color=cpu_c, lw=2, label="NTT, CPU")
    if gpu:
        ax.plot(kk, [r["gpu"]["msm_s"] for r in res["kernels"]], "s-", color=gpu_c, lw=2, label="MSM, GPU")
        ax.plot(kk, [r["gpu"]["ntt_s"] for r in res["kernels"]], "s--", color=gpu_c, lw=2, label="NTT, GPU")
    ax.set(yscale="log", xlabel="log2(size)", ylabel="time (s)", title="Kernels")
    ax.grid(alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "bench.png"), dpi=130)


if __name__ == "__main__":
    main()
