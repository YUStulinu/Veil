//! Writes a Solidity verifier for one verifying key. It runs on the EIP-2537
//! BLS12-381 precompiles (live on Ethereum since Pectra): G1MSM (0x0c) for
//! the linear combination of commitments, PAIRING_CHECK (0x0f) for the final
//! check, and MODEXP (0x05) for the one field inversion. The precompiles
//! check that every point is canonical, on the curve and in the subgroup.

use crate::curve::{g1_generator, g1_to_eip2537, g2_to_eip2537};
use crate::ff::{Field, Fr};
use crate::hash::{hex, keccak256};
use crate::plonk::setup::VerifyingKey;

fn word(x: &Fr) -> String {
    format!("0x{}", hex(&x.to_bytes_be()))
}

pub fn verifier_contract(vk: &VerifyingKey) -> String {
    let mut state0 = b"veil-plonk-v1".to_vec();
    state0.extend_from_slice(&vk.to_bytes());
    let state0 = keccak256(&state0);
    let mut vk_points = vec![];
    for c in &vk.commitments {
        vk_points.extend_from_slice(&g1_to_eip2537(c));
    }
    vk_points.extend_from_slice(&g1_to_eip2537(&g1_generator()));
    let mut g2 = vec![];
    for g in &vk.g2 {
        g2.extend_from_slice(&g2_to_eip2537(g));
    }
    let n_inv = Fr::from_u64(vk.n as u64).inverse().unwrap();
    TEMPLATE
        .replace("{N}", &vk.n.to_string())
        .replace("{LOG_N}", &vk.n.trailing_zeros().to_string())
        .replace("{NUM_PUBLIC}", &vk.num_public.to_string())
        .replace("{OMEGA}", &word(&vk.omega))
        .replace("{N_INV}", &word(&n_inv))
        .replace("{K1}", &word(&vk.k1))
        .replace("{K2}", &word(&vk.k2))
        .replace("{STATE0}", &format!("0x{}", hex(&state0)))
        .replace("{VK_POINTS}", &hex(&vk_points))
        .replace("{G2_POINTS}", &hex(&g2))
}

const TEMPLATE: &str = r#"// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/// Verifies Veil PLONK proofs (KZG over BLS12-381) for one circuit.
/// Generated by `veil export-sol` from the circuit's verifying key.
/// Proof layout (1344 bytes): [a] [b] [c] [z] [t_lo] [t_mid] [t_hi] [W_zeta]
/// [W_zeta_omega] as 128-byte EIP-2537 points, then a(zeta) b(zeta) c(zeta)
/// S1(zeta) S2(zeta) z(zeta omega) as 32-byte words.
contract VeilVerifier {
    uint256 internal constant R = 0x73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001;
    uint256 internal constant N = {N};
    uint256 internal constant LOG_N = {LOG_N};
    uint256 internal constant NUM_PUBLIC = {NUM_PUBLIC};
    uint256 internal constant OMEGA = {OMEGA};
    uint256 internal constant N_INV = {N_INV};
    uint256 internal constant K1 = {K1};
    uint256 internal constant K2 = {K2};
    /// keccak256("veil-plonk-v1" || verifying key): the transcript's start
    bytes32 internal constant STATE0 = {STATE0};
    /// [q_M] [q_L] [q_R] [q_O] [q_C] [S1] [S2] [S3] and the G1 generator
    bytes internal constant VK_POINTS = hex"{VK_POINTS}";
    /// [1]_2, [tau]_2
    bytes internal constant G2_POINTS = hex"{G2_POINTS}";

    struct Ch {
        uint256 beta;
        uint256 gamma;
        uint256 alpha;
        uint256 zeta;
        uint256 v;
        uint256 u;
    }

    function verify(bytes calldata proof, uint256[] calldata pub) external view returns (bool) {
        if (proof.length != 1344 || pub.length != NUM_PUBLIC) return false;
        for (uint256 i = 0; i < pub.length; i++) {
            if (pub[i] >= R) return false;
        }
        uint256[6] memory ev;
        for (uint256 i = 0; i < 6; i++) {
            ev[i] = uint256(bytes32(proof[1152 + 32 * i:1184 + 32 * i]));
            if (ev[i] >= R) return false;
        }
        Ch memory c = challenges(proof, pub);
        (bool ok, uint256[18] memory ks) = scalars(c, ev, pub);
        if (!ok) return false;
        return pairing(proof, c.u, ks);
    }

    function challenges(bytes calldata proof, uint256[] calldata pub) internal pure returns (Ch memory c) {
        bytes32 h = keccak256(abi.encodePacked(STATE0, pub, proof[0:384]));
        c.beta = uint256(h) % R;
        h = keccak256(abi.encodePacked(h));
        c.gamma = uint256(h) % R;
        h = keccak256(abi.encodePacked(h, proof[384:512]));
        c.alpha = uint256(h) % R;
        h = keccak256(abi.encodePacked(h, proof[512:896]));
        c.zeta = uint256(h) % R;
        h = keccak256(abi.encodePacked(h, proof[1152:1344]));
        c.v = uint256(h) % R;
        h = keccak256(abi.encodePacked(h, proof[896:1152]));
        c.u = uint256(h) % R;
    }

    /// The scalars of -(F - E + zeta W + u zeta omega W') over the 18 points
    /// VK_POINTS (9) and the proof's points (9).
    function scalars(Ch memory c, uint256[6] memory ev, uint256[] calldata pub) internal view returns (bool, uint256[18] memory ks) {
        uint256 zn = c.zeta;
        for (uint256 i = 0; i < LOG_N; i++) zn = mulmod(zn, zn, R);
        uint256 zh = addmod(zn, R - 1, R);
        // L_i(zeta) for the public rows, with one inversion
        uint256 m = NUM_PUBLIC == 0 ? 1 : NUM_PUBLIC;
        uint256[] memory den = new uint256[](m);
        uint256[] memory pre = new uint256[](m);
        uint256[] memory ws = new uint256[](m);
        uint256 acc = 1;
        uint256 w = 1;
        for (uint256 i = 0; i < m; i++) {
            ws[i] = w;
            den[i] = addmod(c.zeta, R - w, R);
            pre[i] = acc;
            acc = mulmod(acc, den[i], R);
            w = mulmod(w, OMEGA, R);
        }
        if (acc == 0) return (false, ks);
        uint256 inv = modInverse(acc);
        uint256 l0;
        uint256 pi;
        uint256 base = mulmod(zh, N_INV, R);
        for (uint256 j = m; j > 0; j--) {
            uint256 i = j - 1;
            uint256 di = mulmod(inv, pre[i], R);
            inv = mulmod(inv, den[i], R);
            uint256 li = mulmod(mulmod(ws[i], base, R), di, R);
            if (i == 0) l0 = li;
            if (i < NUM_PUBLIC) pi = addmod(pi, mulmod(R - pub[i], li, R), R);
        }
        uint256 a2 = mulmod(c.alpha, c.alpha, R);
        uint256 permS = mulmod(
            mulmod(c.alpha, addmod(addmod(ev[0], mulmod(c.beta, ev[3], R), R), c.gamma, R), R),
            mulmod(addmod(addmod(ev[1], mulmod(c.beta, ev[4], R), R), c.gamma, R), ev[5], R),
            R
        );
        uint256 r0 = addmod(addmod(pi, R - mulmod(permS, addmod(ev[2], c.gamma, R), R), R), R - mulmod(a2, l0, R), R);
        uint256 bz = mulmod(c.beta, c.zeta, R);
        uint256 permZ = mulmod(
            mulmod(c.alpha, addmod(addmod(ev[0], bz, R), c.gamma, R), R),
            mulmod(addmod(addmod(ev[1], mulmod(bz, K1, R), R), c.gamma, R), addmod(addmod(ev[2], mulmod(bz, K2, R), R), c.gamma, R), R),
            R
        );
        permZ = addmod(permZ, mulmod(a2, l0, R), R);
        uint256 v2 = mulmod(c.v, c.v, R);
        uint256 v3 = mulmod(v2, c.v, R);
        uint256 v4 = mulmod(v3, c.v, R);
        uint256 v5 = mulmod(v4, c.v, R);
        uint256 e = addmod(R - r0, mulmod(c.v, ev[0], R), R);
        e = addmod(e, mulmod(v2, ev[1], R), R);
        e = addmod(e, mulmod(v3, ev[2], R), R);
        e = addmod(e, mulmod(v4, ev[3], R), R);
        e = addmod(e, mulmod(v5, ev[4], R), R);
        e = addmod(e, mulmod(c.u, ev[5], R), R);
        // + terms, negated at the end
        ks[0] = mulmod(ev[0], ev[1], R); // q_M
        ks[1] = ev[0]; // q_L
        ks[2] = ev[1]; // q_R
        ks[3] = ev[2]; // q_O
        ks[4] = 1; // q_C
        ks[5] = v4; // S1
        ks[6] = v5; // S2
        ks[7] = R - mulmod(permS, c.beta, R); // S3
        ks[8] = R - e; // G
        ks[9] = c.v; // a
        ks[10] = v2; // b
        ks[11] = v3; // c
        ks[12] = addmod(permZ, c.u, R); // z
        ks[13] = R - zh; // t_lo
        ks[14] = R - mulmod(zh, zn, R); // t_mid
        ks[15] = R - mulmod(mulmod(zh, zn, R), zn, R); // t_hi
        ks[16] = c.zeta; // W
        ks[17] = mulmod(mulmod(c.u, c.zeta, R), OMEGA, R); // W'
        for (uint256 i = 0; i < 18; i++) ks[i] = (R - ks[i]) % R;
        return (true, ks);
    }

    function pairing(bytes calldata proof, uint256 u, uint256[18] memory ks) internal view returns (bool) {
        bytes memory pts = abi.encodePacked(VK_POINTS, proof[0:1152]);
        bytes memory input = new bytes(18 * 160);
        for (uint256 i = 0; i < 18; i++) {
            uint256 k = ks[i];
            assembly {
                let src := add(add(pts, 32), mul(i, 128))
                let dst := add(add(input, 32), mul(i, 160))
                mcopy(dst, src, 128)
                mstore(add(dst, 128), k)
            }
        }
        (bool ok, bytes memory negRhs) = address(0x0c).staticcall(input);
        if (!ok || negRhs.length != 128) return false;
        (ok, input) = (true, abi.encodePacked(proof[896:1024], uint256(1), proof[1024:1152], u));
        bytes memory lhs;
        (ok, lhs) = address(0x0c).staticcall(input);
        if (!ok || lhs.length != 128) return false;
        bytes memory g2 = G2_POINTS;
        bytes memory g2one = new bytes(256);
        bytes memory g2tau = new bytes(256);
        assembly {
            mcopy(add(g2one, 32), add(g2, 32), 256)
            mcopy(add(g2tau, 32), add(g2, 288), 256)
        }
        bytes memory out;
        (ok, out) = address(0x0f).staticcall(abi.encodePacked(lhs, g2tau, negRhs, g2one));
        return ok && out.length == 32 && uint256(bytes32(out)) == 1;
    }

    function modInverse(uint256 x) internal view returns (uint256) {
        (bool ok, bytes memory out) = address(0x05).staticcall(abi.encodePacked(uint256(32), uint256(32), uint256(32), x, R - 2, R));
        require(ok, "modexp");
        return uint256(bytes32(out));
    }
}
"#;
